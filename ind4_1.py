from datetime import datetime

def main(**kwargs):
    """
    Функция обрабатывает переданные именованные аргументы.
    
    Args:
        **kwargs: Произвольное количество именованных аргументов,
                 где значения - списки из двух чисел
    """
    # Перебор всех пар ключ-значение в словаре kwargs
    for key in kwargs.items():
        # Вычисление результата: проверяет, равны ли оба элемента списка 2
        # key[1] - это значение (список), key[1][0] и key[1][1] - элементы списка
        result = (key[1][0] == 2) + (key[1][1] == 2)
        # Вывод результата для текущего ключа
        print(result)

# Проверка, запущен ли скрипт напрямую
if __name__ == "__main__":
    # Запись времени начала выполнения программы
    start_time = datetime.now()
    
    # Вызов функции main с передачей именованных аргументов
    # Каждый аргумент - список из двух чисел
    main(
        one=[0, 3],
        two=[5, 4], 
        three=[15, 13],
        four=[35, 53],
        five=[133, 15]
    )
    
    # Вычисление времени выполнения программы
    time_costs = datetime.now() - start_time
    # Вывод времени выполнения (исправлена f-строка)
    print(f"Время выполнения программы = {time_costs}")